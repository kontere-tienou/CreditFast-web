import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const moduleUrl = source => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const transpile = source => ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) };
let networkCalls = 0;
globalThis.fetch = () => { networkCalls++; throw new Error('Network forbidden during local workflow'); };
const localUrl = moduleUrl(transpile(await readFile(new URL('../src/api/localWorkflow.ts', import.meta.url), 'utf8')));
const sessionUrl = moduleUrl('export const getAccessToken = () => globalThis.demoToken; export const clearUiSession = () => {};');
const modeUrl = moduleUrl('export const LOCAL_WORKFLOW = true;');
const errorUrl = moduleUrl('export class ApiError extends Error { constructor(message, status) { super(message); this.status = status; } }');
let clientSource = transpile(await readFile(new URL('../src/api/client.ts', import.meta.url), 'utf8'));
clientSource = clientSource.replaceAll("'@/app/session'", JSON.stringify(sessionUrl)).replaceAll("'@/app/runtimeMode'", JSON.stringify(modeUrl)).replaceAll("'./errors'", JSON.stringify(errorUrl)).replaceAll("'./localWorkflow'", JSON.stringify(localUrl)).replace('import.meta.env.VITE_API_URL', 'undefined');
const { apiJson } = await import(moduleUrl(clientSource));
const post = (path, body = {}) => apiJson(path, { method: 'POST', body: JSON.stringify(body) });
async function login(identifier) {
  const email = identifier.includes('@');
  const result = await post(`/auth/${email ? 'staff' : 'client'}/login`, { [email ? 'email' : 'phone']: identifier, password: 'demo-local' });
  globalThis.demoToken = result.token;
  return result;
}

