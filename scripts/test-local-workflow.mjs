assert.equal((await apiJson('/profile')).client.financial_accounts[0].status, 'ACTIF');
const movements = (await apiJson('/profile/financial-accounts/1/transactions')).data;
assert.equal(movements.length, 6);
assert.equal(movements.filter(row => row.status === 'COMPLETED').reduce((sum, row) => sum + (row.direction === 'CREDIT' ? row.amount : -row.amount), 0), 500000);
assert.deepEqual((await apiJson('/profile/financial-accounts/1/transactions')).data, movements, 'History remains stable across reloads');
assert.equal((await apiJson('/profile')).client.financial_accounts[0].available_balance, 500000);
assert.equal((await apiJson('/profile')).client.financial_accounts[0].blocked_balance, 0);
const saved = JSON.parse(storage.get('creditfast:local-workflow:v1'));
saved.profiles[0].financial_accounts[0].blocked_balance = 100000;
storage.set('creditfast:local-workflow:v1', JSON.stringify(saved));
assert.equal((await apiJson('/profile')).client.financial_accounts[0].available_balance, 400000);
assert.equal((await apiJson('/profile/kyc-documents')).data.length, 1);
await login('+22370000003');
